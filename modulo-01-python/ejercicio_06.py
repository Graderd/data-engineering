#Cree una lista con cinco lenguajes de programación.
lenguaje = ["python", "java", "c++", "javascript", "ruby"]

# Imprimir el primer elemento de la lista
print(lenguaje[0])

#Imprima el último lenguaje
print(lenguaje[-1])

#Utilice un bucle for para mostrar todos los lenguajes.
for lang in lenguaje:
    print(f"Lenguaje: {lang}")

# Muestre cuántos lenguajes contiene la lista.
print(f"La lista tiene {len(lenguaje)} lenguajes de programación.")
